// Regenerate lib/wend/words.ts from the `an-array-of-english-words` package.
//
// The package ships 275k words (~2.6MB) and bundling it whole would put all of
// that into the content script. Wend splits ~19 tiles across 4 words, so only
// lengths 3-8 can ever appear; filtering to those cuts it to roughly a third.
//
//   npm install --no-save an-array-of-english-words
//   node scripts/build-wordlist.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const MIN_LEN = 3;
const MAX_LEN = 8;

const require = createRequire(import.meta.url);
const all = require('an-array-of-english-words');

const words = all
  .filter((w) => w.length >= MIN_LEN && w.length <= MAX_LEN && /^[a-z]+$/.test(w))
  .map((w) => w.toUpperCase())
  .sort();

const out = `// GENERATED by scripts/build-wordlist.mjs — do not edit by hand.
// ${words.length} English words of length ${MIN_LEN}-${MAX_LEN}, uppercase.
// Stored as one newline-delimited string: a string literal is markedly cheaper
// to parse than an array literal of the same content.
export const MIN_WORD_LENGTH = ${MIN_LEN};
export const MAX_WORD_LENGTH = ${MAX_LEN};
export const WORDS = ${JSON.stringify(words.join('\n'))};
`;

writeFileSync(new URL('../lib/wend/words.ts', import.meta.url), out);
console.log(`wrote lib/wend/words.ts — ${words.length} words, ${(out.length / 1024).toFixed(0)}KB`);
